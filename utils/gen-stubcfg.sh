#!/usr/bin/env bash
# gen-stubcfg.sh — generate a stubcfg.nix containing every cfg.* option
# declared in modules/cfg together with its default value.
#
# Usage: utils/gen-stubcfg.sh [-o|--out|--output FILE]
#
# By default stubcfg.nix is written to the current working directory.

set -euo pipefail

usage() {
  cat <<'EOF'
Usage: gen-stubcfg.sh [-o|--out|--output FILE]

Parses every option declared under modules/cfg and writes a stubcfg.nix
containing all declared cfg.* options with their default values.

Options:
  -o, --out, --output FILE   Output file (default: ./stubcfg.nix)
  -h, --help                 Show this help
EOF
}

out="stubcfg.nix"

while [[ $# -gt 0 ]]; do
  case "$1" in
    -o|--out|--output)
      if [[ $# -lt 2 ]]; then
        echo "gen-stubcfg.sh: error: '$1' requires an argument" >&2
        exit 2
      fi
      out="$2"
      shift 2
      ;;
    -h|--help)
      usage
      exit 0
      ;;
    *)
      echo "gen-stubcfg.sh: error: unknown argument: $1" >&2
      usage >&2
      exit 2
      ;;
  esac
done

script_dir="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" >/dev/null 2>&1 && pwd -P)"
repo_root="$(cd -- "${script_dir}/.." >/dev/null 2>&1 && pwd -P)"

if ! command -v nix-instantiate >/dev/null 2>&1; then
  echo "gen-stubcfg.sh: error: nix-instantiate not found; this script requires Nix" >&2
  exit 1
fi

if ! command -v jq >/dev/null 2>&1; then
  echo "gen-stubcfg.sh: error: jq not found; this script requires jq" >&2
  exit 1
fi

# Note: nixpkgs is resolved *inside* the helper expression via
# builtins.getFlake (see below), so fetching and importing happen in a
# single Nix evaluation. Resolving a store path here in bash races the
# GC: --find-file can hand back a dead path that passes --check-validity
# but is gone by the time nix-instantiate realises it.

helper="$(mktemp --suffix=-gen-stubcfg.nix)"
trap 'rm -f "$helper"' EXIT

cat >"$helper" <<'HELPER_EOF'
{ repoRoot }:

let
  # Resolved here, not in bash: getFlake fetches and realises the source
  # in the same evaluation that imports it, so the path cannot be GC'd
  # in between. Requires --impure (getFlake), which is passed at the
  # nix-instantiate call site below.
  nixpkgs = (builtins.getFlake "flake:nixpkgs").outPath;

  lib = import "${nixpkgs}/lib";

  eval = lib.evalModules {
    modules = [
      (import "${repoRoot}/modules/cfg")
      # The cfg modules set config.assertions (part of the nixpkgs module set,
      # which is unavailable here); declare it so evalModules accepts it.
      ({ lib, ... }: {
        config._module.check = false;
        options.assertions = lib.mkOption {
          type = lib.types.listOf lib.types.attrs;
          default = [ ];
        };
      })
    ];
  };

  # Render a plain nix value as nix source.
  toNix =
    value:
    if value == null then
      "null"
    else if builtins.isBool value then
      (if value then "true" else "false")
    else if builtins.isInt value then
      builtins.toString value
    else if builtins.isFloat value then
      builtins.toString value
    else if builtins.isString value then
      builtins.toJSON value
    else if builtins.isPath value then
      "/. + ${builtins.toJSON (builtins.toString value)}"
    else if builtins.isList value then
      if value == [ ] then
        "[ ]"
      else
        "[ ${lib.concatStringsSep " " (map toNix value)} ]"
    else if builtins.isAttrs value then
      "{ ${
        lib.concatStringsSep " " (
          lib.mapAttrsToList (name: val: "${lib.strings.escapeNixIdentifier name} = ${toNix val};") value
        )
      } }"
    else
      throw "gen-stubcfg: unsupported default value type";

  # Recursively collect every option declared under options.cfg together
  # with its default value. Options without a default are skipped.
  collect =
    prefix: set:
    lib.concatLists (
      lib.mapAttrsToList (
        name: value:
        let
          path = if prefix == "" then name else "${prefix}.${name}";
        in
        if lib.isAttrs value && value ? _type && value._type == "option" then
          if value ? default then
            [ { inherit path; value = value.default; } ]
          else
            [ ]
        else if lib.isAttrs value then
          collect path value
        else
          [ ]
      ) set
    );

  entries = collect "" eval.options.cfg;

  lines = map (entry: "    ${entry.path} = ${toNix entry.value};") entries;

  body = lib.concatStringsSep "\n" lines;
in
''
{
  cfg = {
${body}
  };
}
''
HELPER_EOF

if [[ "$(dirname -- "$out")" != "." ]]; then
  mkdir -p -- "$(dirname -- "$out")"
fi

generated="$(nix-instantiate --eval --strict --json --impure "$helper" \
  --arg repoRoot "\"${repo_root}\"" | jq -r .)"

{
  printf '# Generated by utils/gen-stubcfg.sh on %s.\n' "$(date -u +%Y-%m-%d)"
  printf '# Contains every cfg.* option declared in modules/cfg with its default value.\n'
  printf '%s\n' "$generated"
} >"$out"

echo "gen-stubcfg.sh: wrote $out"